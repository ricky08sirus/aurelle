"""
Cloudflare R2 storage helpers.
Place at: backend/app/storage.py
"""
import asyncio
import os
import re
import uuid

import boto3
from botocore.config import Config
from botocore.exceptions import ClientError
from dotenv import load_dotenv
from fastapi import HTTPException, UploadFile

load_dotenv()  # finds backend/.env by walking up from this file

BUCKET = os.environ["R2_BUCKET"]
PUBLIC_BASE = os.environ["R2_PUBLIC_BASE_URL"].rstrip("/")

PREFIX = "images/"
MAX_BYTES = 5 * 1024 * 1024  # 5 MB
ALLOWED = {  # content-type -> extension
    "image/jpeg": "jpg",
    "image/png": "png",
    "image/webp": "webp",
    "image/gif": "gif",
}
FOLDER_PATTERN = r"^[a-z0-9_-]{1,40}$"
# Only keys generated by this module are accepted: images/<folder>/<32 hex>.<ext>
KEY_RE = re.compile(r"^images/[a-z0-9_-]{1,40}/[a-f0-9]{32}\.(jpg|png|webp|gif)$")

_s3 = boto3.client(
    "s3",
    endpoint_url=f"https://{os.environ['R2_ACCOUNT_ID']}.r2.cloudflarestorage.com",
    aws_access_key_id=os.environ["R2_ACCESS_KEY_ID"],
    aws_secret_access_key=os.environ["R2_SECRET_ACCESS_KEY"],
    region_name="auto",
    config=Config(signature_version="s3v4"),
)


def public_url(key: str) -> str:
    return f"{PUBLIC_BASE}/{key}"


def _sniff_type(data: bytes) -> str | None:
    """Check the real file bytes; the client-sent content-type can be faked."""
    if data.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if data[:6] in (b"GIF87a", b"GIF89a"):
        return "image/gif"
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "image/webp"
    return None


async def read_and_validate(file: UploadFile) -> tuple[bytes, str]:
    data = await file.read(MAX_BYTES + 1)
    if not data:
        raise HTTPException(400, "Empty file")
    if len(data) > MAX_BYTES:
        raise HTTPException(413, f"File too large (max {MAX_BYTES // 1024 // 1024} MB)")
    ctype = _sniff_type(data)
    if ctype not in ALLOWED:
        raise HTTPException(415, "Only JPEG, PNG, WEBP or GIF images are allowed")
    return data, ctype


def validate_key(key: str) -> str:
    if not KEY_RE.match(key):
        raise HTTPException(400, "Invalid key")
    return key


def folder_of(key: str) -> str:
    return key.split("/")[1]


def make_key(folder: str, ctype: str) -> str:
    return f"{PREFIX}{folder}/{uuid.uuid4().hex}.{ALLOWED[ctype]}"


def _storage_error(e: ClientError) -> HTTPException:
    return HTTPException(502, f"Storage error: {e.response['Error']['Code']}")


async def put(key: str, data: bytes, ctype: str) -> None:
    try:
        await asyncio.to_thread(
            _s3.put_object,
            Bucket=BUCKET,
            Key=key,
            Body=data,
            ContentType=ctype,
            # Keys are unique and never overwritten, so long caching is safe.
            CacheControl="public, max-age=31536000, immutable",
        )
    except ClientError as e:
        raise _storage_error(e)


async def exists(key: str) -> bool:
    try:
        await asyncio.to_thread(_s3.head_object, Bucket=BUCKET, Key=key)
        return True
    except ClientError as e:
        if e.response["Error"]["Code"] in ("404", "NoSuchKey", "NotFound"):
            return False
        raise _storage_error(e)


async def delete(key: str) -> None:
    try:
        await asyncio.to_thread(_s3.delete_object, Bucket=BUCKET, Key=key)
    except ClientError as e:
        raise _storage_error(e)


async def list_objects(folder: str, limit: int, cursor: str | None):
    params = {
        "Bucket": BUCKET,
        "Prefix": f"{PREFIX}{folder + '/' if folder else ''}",
        "MaxKeys": limit,
    }
    if cursor:
        params["ContinuationToken"] = cursor
    try:
        return await asyncio.to_thread(_s3.list_objects_v2, **params)
    except ClientError as e:
        raise _storage_error(e)